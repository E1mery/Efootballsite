// Alias for backwards compatibility
export const LIGUE_1_TEAMS = SERIE_A_TEAMS;

export const ALL_REAL_TEAMS: RealFootballTeam[] = [
  ...PREMIER_LEAGUE_TEAMS,
  ...LA_LIGA_TEAMS,
  ...SERIE_A_TEAMS,
];

/**
 * Returns available real football teams for a player's division.
 */
export function getTeamsForDivision(division: string): RealFootballTeam[] {
  if (division === "Division 1") {
    return PREMIER_LEAGUE_TEAMS;
  }
  if (division === "Division 2") {
    return LA_LIGA_TEAMS;
  }
  if (division === "Division 3") {
    return SERIE_A_TEAMS;
  }
  return ALL_REAL_TEAMS;
}

/**
 * Find team by ID or name
 */
export function findTeam(idOrName?: string | null): RealFootballTeam | undefined {
  if (!idOrName) return undefined;
  const normalized = idOrName.trim().toLowerCase();
  return ALL_REAL_TEAMS.find(
    (t) =>
      t.id.toLowerCase() === normalized ||
      t.name.toLowerCase() === normalized ||
      t.shortName.toLowerCase() === normalized
  );
}

/**
 * Resolves avatar or team crest for a player
 */
export function resolvePlayerAvatar(player?: {
  avatar?: string | null;
  realTeam?: string | null;
  gamerTag?: string;
}): string {
  if (player?.avatar && player.avatar.startsWith("http")) {
    return player.avatar;
  }
  if (player?.realTeam) {
    const team = findTeam(player.realTeam);
    if (team) return team.logo;
  }
  // Default fallback avatar placeholder or initial
  return `https://api.dicebear.com/7.x/bottts/svg?seed=${encodeURIComponent(player?.gamerTag || "Player")}`;
}
